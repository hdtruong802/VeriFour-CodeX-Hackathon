    fun t(
        key: String,
        locale: AppLocale,
        params: Map<String, Any> = emptyMap()
    ): String {
        val map = when (locale) {
            AppLocale.VI -> vi
            AppLocale.EN -> en
            AppLocale.KO -> ko
        }
        var template = map[key] ?: en[key] ?: vi[key] ?: key
        for ((k, v) in params) {
            template = template.replace("{$k}", v.toString())
        }
        return template
    }

    fun formatNumber(value: Int, locale: AppLocale): String {
        val jLocale = when (locale) {
            AppLocale.VI -> JavaLocale.forLanguageTag("vi-VN")
            AppLocale.EN -> JavaLocale.US
            AppLocale.KO -> JavaLocale.KOREA
        }
        return NumberFormat.getNumberInstance(jLocale).format(value)
    }

    fun localizedCollectionPoint(
        pointOrName: String,
        locale: AppLocale
    ): Pair<String, String> {
        val meta: CollectionPointMeta? = COLLECTION_POINTS.firstOrNull {
            it.canonicalName == pointOrName || it.id == pointOrName
        }
        return if (meta != null) {
            t(meta.nameKey, locale) to t(meta.addressKey, locale)
        } else {
            pointOrName to ""
        }
    }
